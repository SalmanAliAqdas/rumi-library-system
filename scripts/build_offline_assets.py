"""Rebuild code-drawn PNG icons and Python Unicode parity data, without dependencies."""

import json
import struct
import sys
import unicodedata
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def icon(size):
    rows = []
    for y in range(size):
        row = bytearray()
        for x in range(size):
            fx, fy = x / size, y / size
            # Open book drawn inside the central maskable safe zone.
            page = 0.23 < fx < 0.77 and 0.31 < fy < 0.68
            gold = page and (abs(fx - 0.5) < 0.012 or fy < 0.33 or fy > 0.66 or fx < 0.25 or fx > 0.75)
            line = (
                page
                and (0.39 < fy < 0.41 or 0.47 < fy < 0.49 or 0.55 < fy < 0.57)
                and (0.28 < fx < 0.46 or 0.54 < fx < 0.72)
            )
            row.extend((215, 191, 137) if gold or line else (250, 247, 240) if page else (52, 79, 67))
        rows.append(b"\x00" + row)

    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))

    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 2, 0, 0, 0))
        + chunk(b"IDAT", zlib.compress(b"".join(rows)))
        + chunk(b"IEND", b"")
    )


def main():
    sys.path.insert(0, str(ROOT))
    from catalog.templatetags.library_ui import LABELS

    destination = ROOT / "static" / "offline"
    destination.mkdir(exist_ok=True)
    for size in (192, 512):
        (destination / f"icon-{size}.png").write_bytes(icon(size))
    fold = {
        chr(code).lower(): chr(code).casefold()
        for code in range(0x110000)
        if chr(code).casefold() != chr(code).lower()
    }
    whitespace = [code for code in range(0x110000) if chr(code).isspace()]
    data = {"unicode_version": unicodedata.unidata_version, "casefold": fold, "whitespace": whitespace}
    (destination / "unicode-data.js").write_text(
        "// Generated by scripts/build_offline_assets.py\nexport default "
        + json.dumps(data, ensure_ascii=True, sort_keys=True)
        + ";\n",
        encoding="utf-8",
    )
    (destination / "labels.js").write_text(
        "// Generated from the Python UI catalogues.\nexport default "
        + json.dumps(LABELS, ensure_ascii=True, sort_keys=True)
        + ";\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
